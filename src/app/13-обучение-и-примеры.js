function sunTimes(dateStr,city){
  const p=dateStr.split('-').map(Number);if(p.length<3||!p[0])return null;
  const N=Math.floor((Date.UTC(p[0],p[1]-1,p[2])-Date.UTC(p[0],0,0))/864e5),rad=Math.PI/180,g=2*Math.PI/365*(N-1);
  const eq=229.18*(0.000075+0.001868*Math.cos(g)-0.032077*Math.sin(g)-0.014615*Math.cos(2*g)-0.040849*Math.sin(2*g));
  const dec=0.006918-0.399912*Math.cos(g)+0.070257*Math.sin(g)-0.006758*Math.cos(2*g)+0.000907*Math.sin(2*g)-0.002697*Math.cos(3*g)+0.00148*Math.sin(3*g);
  const c=Math.cos(90.833*rad)/(Math.cos(city.lat*rad)*Math.cos(dec))-Math.tan(city.lat*rad)*Math.tan(dec);
  if(c>1||c<-1)return null;
  const ha=Math.acos(c)/rad;
  return {rise:720-4*(city.lon+ha)-eq+300,set:720-4*(city.lon-ha)-eq+300};
}
